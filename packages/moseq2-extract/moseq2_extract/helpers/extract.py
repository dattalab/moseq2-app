def write_extracted_chunk_to_h5(
    h5_file, results, config_data, scalars, frame_range, offset
):
    """

    Write extracted frames, frame masks, and scalars to an open h5 file.

    Args:
    h5_file (H5py.File): open results_00 h5 file to save data in.
    results (dict): extraction results dict.
    config_data (dict): dictionary containing extraction parameters (autogenerated)
    scalars (list): list of keys to scalar attribute values
    frame_range (range object): the chunk's positions in the h5, counted from the first extracted frame
    offset (int): frame offset

    Returns:
    """

    # Writing computed scalars to h5 file
    for scalar in scalars:
        h5_file[f"scalars/{scalar}"][frame_range] = results["scalars"][scalar][offset:]

    # Writing frames and mask to h5
    h5_file["frames"][frame_range] = results["depth_frames"][offset:]
    h5_file["frames_mask"][frame_range] = results["mask_frames"][offset:]

    # Writing flip classifier results to h5
    if config_data["flip_classifier"]:
        h5_file["metadata/extraction/flips"][frame_range] = results["flips"][offset:]


def set_tracking_model_parameters(
    results, min_height, tracking_model_ll_clip, chunk_overlap, **kwargs
):
    """
    Threshold and clip the masked frame data if use_tracking_model = True and update results.

    Args:
    results (dict): dict of extracted depth frames and mask frames to threshold to update; output of extract_chunk().
    min_height (int): distance from floor to threshold out of extracted image.
    tracking_model_ll_clip (numpy.ndarray): clipped frame regions based on EM loglikelihoods computed in extract_chunk().
    chunk_overlap (int): number of frames each extracted chunk is overlapping with the next.

    Returns:
    results (dict): updated results dict with thresholded and clipped mask_frames.
    tracking_init_mean (float): mean value for EM Tracking
    tracking_init_cov (float): covariance value for EM Tracking
    """

    # Thresholding and clipping EM-tracked frame mask data
    results["mask_frames"][
        results["depth_frames"] < min_height
    ] = tracking_model_ll_clip
    results["mask_frames"][
        results["mask_frames"] < tracking_model_ll_clip
    ] = tracking_model_ll_clip

    # Updating EM tracking estimators
    tracking_init_mean = results["parameters"]["mean"][-(chunk_overlap + 1)]
    tracking_init_cov = results["parameters"]["cov"][-(chunk_overlap + 1)]

    return results, tracking_init_mean, tracking_init_cov


def make_output_movie(results, config_data, offset=0):
    """
    Create an array for output movie with filtered video and cropped mouse on the top left

    Args:
    results (dict): dict of extracted depth frames, and original raw chunk to create an output movie.
    config_data (dict): dict of extraction parameters containing the crop sizes used in the extraction.
    offset (int): current offset being used, automatically set if chunk_overlap > 0

    Returns:
    output_movie (numpy.ndarray): output movie to write to mp4 file.
    """

    # Create empty array for output movie with filtered video and cropped mouse on the top left
    nframes, rows, cols = results["chunk"][offset:].shape
    output_movie = np.zeros(
        (
            nframes,
            rows + config_data["crop_size"][0],
            cols + config_data["crop_size"][1],
        ),
        "uint16",
    )

    # Populating array with filtered and cropped videos
    output_movie[:, : config_data["crop_size"][0], : config_data["crop_size"][1]] = (
        results["depth_frames"][offset:]
    )
    output_movie[:, config_data["crop_size"][0] :, config_data["crop_size"][1] :] = (
        results["chunk"][offset:]
    )

    return output_movie


def _orientation_before_next_chunk(orientation, overlap, previous_orientation):
    """
    The orientation the next chunk's first frame is resolved against: that of the
    last frame with a mouse before the next chunk starts. The next chunk extracts
    this chunk's last ``overlap`` frames again, so those are not counted.

    Args:
    orientation (np.ndarray): this chunk's unwrapped orientation per frame, NaN where no mouse was found.
    overlap (int): frames the next chunk shares with this one (chunk_overlap).
    previous_orientation (float): the orientation carried into this chunk, kept when this chunk's frames
        before the next chunk hold no mouse.

    Returns:
    (float): the orientation to carry, or previous_orientation.
    """
    before_next = orientation[: max(len(orientation) - overlap, 0)]
    found = before_next[~np.isnan(before_next)]
    return found[-1] if found.size else previous_orientation


def process_extract_batches(
    input_file,
    config_data,
    bground_im,
    roi,
    frame_batches,
    str_els,
    output_mov_path,
    scalars=None,
    h5_file=None,
    video_pipe=None,
    first_frame_idx=0,
    **kwargs,
):
    """
    Compute extracted frames and save them to h5 files and avi files.

    Args:
    input_file (str): path to depth file
    config_data (dict): dictionary containing extraction parameters (autogenerated)
    bground_im (numpy.ndarray):  background image
    roi (numpy.ndarray): roi image
    frame_batches (list): list of batches of frames to serially process.
    str_els (dict): dictionary containing OpenCV StructuringElements
    output_mov_path (str): path and filename of the output movie generated by the extraction
    scalars (list): list of keys to scalar attribute values
    h5file (h5py.File): opened h5 file to write extracted batches to
    video_pipe (_VideoWriter): the open preview movie being written.
    first_frame_idx (int): the recording's index of the first extracted frame; the
        batches hold recording indices and the h5 holds the extracted frames from 0.
    kwargs (dict): Extra keyword arguments.

    Returns:
    """

    tracking_init_mean = config_data.pop("tracking_init_mean", None)
    tracking_init_cov = config_data.pop("tracking_init_cov", None)
    # the heading carried from one chunk to the next
    previous_orientation = None

    for i, frame_range in enumerate(tqdm(frame_batches, desc="Processing batches")):
        raw_chunk = load_movie_data(
            input_file, frame_range, frame_size=bground_im.shape[::-1], **config_data
        )

        offset = config_data["chunk_overlap"] if i > 0 else 0

        # Get crop-rotated frame batch
        results = extract_chunk(
            **config_data,
            **str_els,
            chunk=raw_chunk,
            roi=roi,
            bground=bground_im,
            tracking_init_mean=tracking_init_mean,
            tracking_init_cov=tracking_init_cov,
            previous_orientation=previous_orientation,
        )
        previous_orientation = _orientation_before_next_chunk(
            results["unwrapped_orientation"], config_data["chunk_overlap"], previous_orientation
        )

        if config_data["use_tracking_model"]:
            # threshold and clip mask frames from EM tracking results
            results, tracking_init_mean, tracking_init_cov = (
                set_tracking_model_parameters(results, **config_data)
            )

        # Offsetting frame chunk by CLI parameter defined option: chunk_overlap
        frame_range = frame_range[offset:]

        if h5_file is not None:
            h5_range = range(
                frame_range.start - first_frame_idx, frame_range.stop - first_frame_idx
            )
            write_extracted_chunk_to_h5(
                h5_file, results, config_data, scalars, h5_range, offset
            )

        # Create array for output movie with filtered video and cropped mouse on the top left
        output_movie = make_output_movie(results, config_data, offset)

        # Writing frame batch to mp4 file
        video_pipe = write_frames_preview(
            output_mov_path,
            output_movie,
            pipe=video_pipe,
            close_pipe=False,
            fps=config_data["fps"],
            frame_range=list(frame_range),
            depth_max=config_data["max_height"],
            depth_min=config_data["min_height"],
            progress_bar=config_data.get("progress_bar", False),
        )

    # Check if video is done writing. If not, wait.
    if video_pipe is not None:
        video_pipe.communicate()


def _already_extracted(recording, config_data, output_dir=None):
    """
    Whether ``extract_wrapper`` would skip this recording as already extracted.

    Args:
    recording (str): path to the recording.
    config_data (dict): the settings it is extracted with.
    output_dir (str): the output folder passed to the extraction, or None for the config's.

    Returns:
    (bool): True when its results yaml says the extraction finished.
    """
    from moseq2_extract.helpers.wrappers import session_output_dir

    if output_dir is None:
        output_dir = config_data.get("output_dir", "proc")
    index = config_data.get("bg_roi_index", 0)
    if isinstance(index, (list, tuple)):
        index = index[0]
    folder = session_output_dir(recording, output_dir)
    return check_completion_status(join(folder, f"results_{index:02d}.yaml"))


def run_local_extract(
    to_extract,
    config_file,
    skip_extracted=False,
    num_frames=None,
    output_dir=None,
    cli_options=None,
):
    """
    Run the extract command on given list of sessions to extract on a local platform.

    Args:
    to_extract (list): list of paths to files to extract
    config_file (str): path to configuration file containing pre-configured extract and ROI
    skip_extracted (bool): Whether to skip already extracted session.
    num_frames (int): number of frames to extract from each session. If None, all frames are extracted.
    output_dir (str): output directory for each session. If None, the config file's output_dir, else "proc".
    cli_options (dict): parameters typed on the command line, applied over the config file and each session's config.

    Returns:
    failures (list): (path, exception) for each recording that could not be extracted, in the order tried.
    """
    from moseq2_extract.gui import extract_command

    # which session config values are not used, said once for every recording rather than per recording
    resolved = recording_configs(config_file, to_extract, cli_options)
    message = resolved.message(
        [
            ext
            for ext in to_extract
            if not (skip_extracted and _already_extracted(ext, resolved.configs[ext], output_dir))
        ]
    )
    if message:
        print(message)

    failures = []
    n_skipped = 0
    for ext in tqdm(to_extract, desc="Extracting Sessions"):
        try:
            result = extract_command(
                ext,
                output_dir,
                config_file=config_file,
                num_frames=num_frames,
                skip=skip_extracted,
                cli_options=cli_options,
                explain_settings=False,
            )
        except Exception as e:
            print("Unexpected error:", e)
            print("could not extract", ext)
            failures.append((ext, e))
        else:
            if result is None:
                n_skipped += 1

    print(extraction_summary(len(to_extract), n_skipped, failures))
    return failures


def extraction_summary(n_recordings, n_skipped, failures):
    """
    Summarize a batch of extractions: how many were extracted, and each failure with its error.

    Args:
    n_recordings (int): number of recordings the batch went through.
    n_skipped (int): number skipped because they were already extracted; counted as neither extracted nor failed.
    failures (list): (path, exception) for each recording that could not be extracted.

    Returns:
    (str): the summary.
    """
    n_tried = n_recordings - n_skipped
    n_extracted = n_tried - len(failures)
    head = f"Extracted {n_extracted} of {n_tried} recordings"
    skipped = f"{n_skipped} already extracted and skipped"
    if not failures:
        return head + (f" ({skipped})." if n_skipped else ".")
    head += f"; {len(failures)} failed"
    lines = [head + (f" ({skipped})." if n_skipped else "."), "Failed:"]
    for path, error in failures:
        lines.append(f"  {path}")
        message = f"{type(error).__name__}: {error}"
        lines.extend(f"    {line}" for line in message.splitlines())
    lines.append(
        "Fix the problem each error names, then run the extraction again. Recordings already "
        "extracted are skipped: the notebook skips them when skip_extracted is True, and "
        "batch-extract leaves them out unless --skip-checks is given (with --skip-checks, "
        "--skip-completed skips them)."
    )
    return "\n".join(lines)


def run_slurm_extract(
    input_dir,
    to_extract,
    config_data,
    skip_extracted=False,
    num_frames=None,
    cli_options=None,
):
    """
    Write one sbatch command per session to extract it on a SLURM cluster, and submit them if run_cmd is set.

    Each session is extracted with the settings ``recording_configs`` resolves: the arena tool's settings from its
    entry in the session config, every other setting from the config file, and the options typed on the command
    line over both. Each session gets a config.yaml of its own in its output directory whenever there is a session
    config or a typed option.

    Args:
    input_dir (str): directory the sessions were found in; extract_out_script is written there.
    to_extract (list): list of paths to files to extract
    config_data (dict): batch-extract parameters, including config_file, session_config_path, output_dir and the SLURM settings.
    skip_extracted (bool): Whether to skip already extracted session.
    num_frames (int): number of frames to extract from each session. If None, all frames are extracted.
    cli_options (dict): parameters typed on the command line, applied over the config file and each session's config.
    """

    assert (
        "extract_out_script" in config_data
    ), "Need to supply extract_out_script to save extract commands"
    # expand input_dir absolute path
    input_dir = abspath(input_dir)

    resolved = recording_configs(config_data["config_file"], to_extract, cli_options)
    # each session reads a config.yaml written to its output directory when its
    # parameters can differ from the config file's
    session_config_files = exists(resolved.session_config_path) or bool(cli_options)

    message = resolved.message(
        [
            depth_file
            for depth_file in to_extract
            if not (
                skip_extracted
                and check_completion_status(
                    join(dirname(depth_file), config_data["output_dir"], "results_00.yaml")
                )
            )
        ]
    )
    if message:
        print(message)

    if session_config_files:
        for depth_file in to_extract:
            output_dir = join(dirname(depth_file), config_data["output_dir"])

            # ensure output_dir exists
            if not exists(output_dir):
                makedirs(output_dir)

            # the recording's settings: the arena tool's from its session config entry,
            # the rest from the config file, typed options over both
            write_yaml(resolved.configs[depth_file], join(output_dir, "config.yaml"))

    # Construct sbatch command for slurm
    commands = ""
    for depth_file in to_extract:
        output_dir = join(dirname(depth_file), config_data["output_dir"])

        # skip session if skip_extracted is true and the session is already extracted
        if skip_extracted and check_completion_status(
            join(output_dir, "results_00.yaml")
        ):
            continue

        # set up config file
        if session_config_files:
            config_file = join(output_dir, "config.yaml")
        else:
            config_file = config_data["config_file"]

        # construct command
        frames = f" --num-frames {num_frames}" if num_frames is not None else ""
        base_command = f'moseq2-extract extract --config-file {config_file}{frames} {depth_file}; "\n'
        prefix = f'sbatch -c {config_data["ncpus"] if config_data["ncpus"] > 0 else 1} --mem={config_data["memory"]} '
        prefix += f'-p {config_data["partition"]} -t {config_data["wall_time"]} --wrap "{config_data["prefix"]}'
        commands += prefix + base_command

    # Ensure output directory exists
    config_data["extract_out_script"] = join(
        input_dir, config_data["extract_out_script"]
    )
    with open(config_data["extract_out_script"], "w") as f:
        f.write(commands)
    print("Commands saved to:", config_data["extract_out_script"])

    # Print command
    if config_data["get_cmd"]:
        print("Listing extract commands...\n")
        print(commands)

    # Run command using system
    if config_data["run_cmd"]:
        print("Running extract commands")
        system(commands)
